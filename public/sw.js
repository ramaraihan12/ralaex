const CACHE_NAME = 'ralaex-v2'

// Only static files are cached. Pages and Supabase calls always go to the
// network so balances never come from an old copy.
const STATIC_PATH = /^\/(icons\/|logo|favicon\.ico|manifest\.json)/

self.addEventListener('install', () => {
  self.skipWaiting()
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((cacheNames) =>
      Promise.all(
        cacheNames
          .filter((name) => name !== CACHE_NAME)
          .map((name) => caches.delete(name))
      )
    )
  )
  self.clients.claim()
})

self.addEventListener('fetch', (event) => {
  const { request } = event
  if (request.method !== 'GET') return

  const url = new URL(request.url)
  if (url.origin !== self.location.origin) return
  if (!STATIC_PATH.test(url.pathname)) return

  event.respondWith(
    caches.match(request).then((cached) => {
      const network = fetch(request).then((response) => {
        if (response.ok) {
          const copy = response.clone()
          caches.open(CACHE_NAME).then((cache) => cache.put(request, copy))
        }
        return response
      })
      return cached || network.catch(() => new Response('Offline', { status: 503 }))
    })
  )
})
